@pytest.fixture
def minimal_vault(tmp_path: Path):
    """Create a minimal valid Brain vault structure + stub BRAIN.md for testing."""
    # Create all 8 top-level folders
    folders = {
        "capture": "00 - CAPTURE",
        "active": "01 - ACTIVE",
        "resources": "02 - RESOURCES",
        "system": "03 - SYSTEM",
        "generated": "04 - GENERATED",
        "queue": "05 - QUEUE",
        "calendar": "06 - CALENDAR",
        "archive": "07 - ARCHIVE",
    }
    for name in folders.values():
        (tmp_path / name).mkdir(parents=True, exist_ok=True)

    # GENERATED subs
    for sub in ["briefings", "summaries", "analyses", "drafts", "consolidated"]:
        (tmp_path / "04 - GENERATED" / sub).mkdir(parents=True, exist_ok=True)

    # Minimal BRAIN.md (required for read_brain_md)
    brain = tmp_path / "03 - SYSTEM" / "BRAIN.md"
    brain.write_text(
        "# BRAIN.md — Test\n\n"
        "## 1. Identity\nTest user\n\n"
        "## 4. Current Priorities\n- P1: Fix vault\n\n"
        "## 3. Active Projects\n| Engram | In progress |\n\n"
        , encoding="utf-8"
    )

    # Some daily for testing
    daily_dir = tmp_path / "01 - ACTIVE" / "daily"
    daily_dir.mkdir(exist_ok=True)
    (daily_dir / "2026-05-20.md").write_text(
        "# 2026-05-20 — Daily Note\n\n**Top 3 Today:**\n- Test vault rules\n\n## Open Loops\n- None\n",
        encoding="utf-8"
    )

    v = Vault(tmp_path)
    yield v

    # Cleanup handled by tmp_path


