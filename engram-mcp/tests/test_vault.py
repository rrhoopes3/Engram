def test_safe_path_blocks_traversal(minimal_vault):
    v = minimal_vault
    with pytest.raises(VaultError, match="traversal blocked"):
        v._safe_path("../../etc/passwd")
    with pytest.raises(VaultError, match="traversal blocked"):
        v._safe_path("03 - SYSTEM/../../../evil.md")


def test_write_briefing_date_validation_and_containment(minimal_vault):
    v = minimal_vault
    # Good write
    p = v.write_briefing("2026-05-22", "# Good briefing\nRules honored.")
    assert p.exists()
    assert "2026-05-22-morning.md" in str(p)
    assert "04 - GENERATED" in str(p)
    assert "briefings" in str(p)
    assert "Generated by engram-mcp" in p.read_text(encoding="utf-8")

    # Bad date (the original escape vector)
    with pytest.raises(VaultError, match="Invalid date"):
        v.write_briefing("../../evil", "bad content")

    # Bad sub via internal (defense in depth)
    with pytest.raises(VaultError, match="Invalid GENERATED subfolder"):
        v._write_to_generated("evil", "x.md", "x")

    # Evil filename
    with pytest.raises(VaultError, match="Unsafe filename"):
        v._write_to_generated("briefings", "../pwned.md", "x")


def test_archive_never_deletes(minimal_vault):
    v = minimal_vault
    # Create a temp file in CAPTURE to "archive"
    cap_file = v.root / "00 - CAPTURE" / "test-capture.md"
    cap_file.write_text("test content for archive", encoding="utf-8")
    assert cap_file.exists()

    archived = v.archive_file("00 - CAPTURE/test-capture.md", reason="test")
    assert not cap_file.exists(), "Original must be gone (moved, never deleted)"
    assert archived.exists()
    assert "07 - ARCHIVE" in str(archived)
    assert "--test-capture.md" in archived.name
    content = archived.read_text(encoding="utf-8")
    assert "test content" in content


